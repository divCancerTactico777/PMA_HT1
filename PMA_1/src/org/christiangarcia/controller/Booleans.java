
package org.christiangarcia.controller;

public class Booleans {

public boolean mayorEdad(int edad) {
    return edad >= 18;
}
public boolean AND(boolean a, boolean b) {
    return a & b;
}
public boolean Or(boolean a, boolean b) {
    return a | b;
}
public boolean NOT(boolean dato) {
    return !dato;
}
}
